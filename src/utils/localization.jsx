/**
 * Custom hook to get translation function
 * @returns {Function} Translation function
 */
export function useTranslation() {
  const { language } = useLanguage();

  const t = (key) => {
    const keys = key.split('.');
    let value = translations[language];

    for (const k of keys) {
      value = value?.[k];
    }

    return value || key;
  };

  return { t, language };
}

